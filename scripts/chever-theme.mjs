import fs from 'node:fs';
const tokens = JSON.parse(fs.readFileSync(new URL('../constants/chever-brand.json', import.meta.url)));
const vars = Object.entries(tokens).map(([k, v]) => `  --ch-${k.replace(/[A-Z]/g, c => '-' + c.toLowerCase())}: ${v};`).join('\n');
const css = `/* Generated by node scripts/chever-theme.mjs; do not edit. */\n:root {\n${vars}\n}\n`;
const path = new URL('../web-v3/brand-tokens.css', import.meta.url);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(path, 'utf8') !== css) throw Error('Regenerate brand-tokens.css');
} else fs.writeFileSync(path, css);
